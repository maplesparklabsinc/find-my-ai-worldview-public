#!/usr/bin/env node
// Generates app/theme.css (the Tailwind theme and CSS variables) from
// design/tokens.json. Never edit app/theme.css by hand; change the tokens and
// run `npm run tokens`. A unit test fails if the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TOKENS_PATH = join(ROOT, "design", "tokens.json");
export const OUT_PATH = join(ROOT, "app", "theme.css");

// Text styles the "Larger text" control scales (docs/01-product-spec.md 5.3).
const SCALED_BY_LARGER_TEXT = new Set(["statement", "option"]);
// Breakpoint the tokens' "on screens wider than Npx" notes refer to.
const WIDE_NOTE = /(\d+)px\/(\d+)px on screens wider than (\d+)px/;

const rem = (px) => {
  const n = typeof px === "number" ? px : Number(String(px).replace(/px$/, ""));
  if (!Number.isFinite(n)) throw new Error(`not a px value: ${px}`);
  return `${+(n / 16).toFixed(4)}rem`;
};

export function buildTokensCss(tokens) {
  const out = [];
  const line = (s = "") => out.push(s);
  line(`/* GENERATED by scripts/build-tokens.mjs from design/tokens.json (version ${tokens.version}). Do not edit. */`);
  line();

  const themes = tokens.color.themes.map((t) => t.id);
  if (!themes.includes("light") || !themes.includes("dark")) throw new Error("tokens need light and dark themes");
  const colors = tokens.color.tokens;

  line("@theme {");
  line("  --color-*: initial;");
  for (const c of colors) line(`  --color-${c.name}: ${c.value.light};`);
  line(`  --font-sans: var(--font-sans-loaded, ${tokens.type.families.sans.split(",")[0]}), ${tokens.type.families.sans};`);
  for (const t of tokens.radius.tokens) {
    const name = t.name.replace(/^radius-/, "");
    line(`  --radius-${name}: ${t.value === "999px" ? "999px" : rem(t.value)};`);
  }
  for (const t of tokens.spacing.tokens) {
    const m = /^space-(\d+)$/.exec(t.name);
    if (m) {
      // Tailwind's spacing scale is 4px per step, so space-N is already p-N, gap-N and so on.
      if (Number(t.value.replace("px", "")) !== Number(m[1]) * 4) throw new Error(`${t.name} is not ${m[1]} x 4px`);
      continue;
    }
    if (t.name.startsWith("measure-")) line(`  --container-${t.name}: ${rem(t.value)};`);
    else line(`  --spacing-${t.name}: ${rem(t.value)};`);
  }
  line("}");
  line();

  line("@media (prefers-color-scheme: dark) {");
  line("  :root {");
  for (const c of colors) line(`    --color-${c.name}: ${c.value.dark};`);
  line("  }");
  line("}");
  line();

  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const scale = SCALED_BY_LARGER_TEXT.has(s.name) ? " * var(--larger-text, 1)" : "";
      const size = (px) => (scale ? `calc(${rem(px)}${scale})` : rem(px));
      line(`@utility type-${s.name} {`);
      line(`  font-family: var(--font-sans);`);
      line(`  font-size: ${size(s.fontSize)};`);
      line(`  line-height: ${size(s.lineHeight)};`);
      line(`  font-weight: ${s.fontWeight};`);
      const wide = WIDE_NOTE.exec(s.usage ?? "");
      if (wide) {
        line(`  @media (width > ${rem(wide[3])}) {`);
        line(`    font-size: ${size(wide[1])};`);
        line(`    line-height: ${size(wide[2])};`);
        line("  }");
      }
      line("}");
      line();
    }
  }
  line("/* The \"Larger text\" control sets this class on the quiz; it scales statements and options by about 20%. */");
  line(".larger-text {");
  line("  --larger-text: 1.2;");
  line("}");
  return out.join("\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = buildTokensCss(JSON.parse(readFileSync(TOKENS_PATH, "utf8")));
  writeFileSync(OUT_PATH, css);
  console.log(`wrote ${OUT_PATH}`);
}
