// Freeze a released content version, so results saved under it always render
// with the wording they were scored with (CLAUDE.md non-negotiable 4).
//
// Copies the content files results depend on into
// lib/content/releases/<scoring>-<taxonomy>-<item bank>-<narratives>/ and
// regenerates lib/content/releases/index.ts, which bundles every release.
// A release, once frozen, never changes: if the folder exists with different
// files the script refuses (a content change without a version bump).
//
//   npm run content:freeze                 # the current content/ files
//   npm run content:freeze -- --rev <git>  # the content/ files at a git revision
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "lib/content/releases");
const FILES = {
  items: "items.json",
  config: "scoring-config.json",
  perspectives: "perspectives.json",
  narratives: "narratives.json",
  baseRates: "base-rates.json",
  copy: "copy.json",
};
// From copy.json only what gives a result its meaning: country names and the
// source lines quoted on it. Labels and buttons stay current, and copy can
// change without a content version bump.
const pick = { copy: (j) => ({ countries: j.countries, evidence_sources: j.evidence_sources }) };

const args = process.argv.slice(2);
const rev = args.includes("--rev") ? args[args.indexOf("--rev") + 1] : null;

function read(name) {
  const file = FILES[name];
  const text = rev
    ? execFileSync("git", ["show", `${rev}:content/${file}`], { cwd: root, encoding: "utf8" })
    : readFileSync(join(root, "content", file), "utf8");
  const json = JSON.parse(text);
  return pick[name] ? pick[name](json) : json;
}

export function releaseKey(v) {
  return `${v.scoring}-${v.taxonomy}-${v.item_bank}-${v.narratives}`;
}

const data = Object.fromEntries(Object.keys(FILES).map((k) => [k, read(k)]));
const key = releaseKey({
  scoring: data.config.scoring_version,
  taxonomy: data.perspectives.taxonomy_version,
  item_bank: data.items.item_bank_version,
  narratives: data.narratives.narratives_version,
});
const dir = join(out, key);
const text = (j) => `${JSON.stringify(j, null, 2)}\n`;

if (existsSync(dir)) {
  const changed = Object.entries(FILES)
    .filter(([k, f]) => readFileSync(join(dir, f), "utf8") !== text(data[k]))
    .map(([, f]) => f);
  if (changed.length > 0) {
    console.error(
      `Release ${key} is already frozen and ${changed.join(", ")} differ. ` +
        "Content changed without a version bump: bump the version of what changed, then freeze again.",
    );
    process.exit(1);
  }
  console.log(`Release ${key} is already frozen and unchanged.`);
} else {
  mkdirSync(dir, { recursive: true });
  for (const [k, f] of Object.entries(FILES)) writeFileSync(join(dir, f), text(data[k]));
  console.log(`Froze release ${key}${rev ? ` from ${rev}` : ""}.`);
}

// Regenerate the index of every frozen release.
const keys = readdirSync(out, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
const lines = [
  "// Generated by scripts/freeze-content.mjs (npm run content:freeze). Do not edit.",
  "// Every released content version, keyed by scoring-taxonomy-itembank-narratives.",
  'import type { RawRelease } from "@/lib/content/release";',
];
keys.forEach((k, n) => {
  for (const [name, f] of Object.entries(FILES)) lines.push(`import ${name}${n} from "./${k}/${f}";`);
});
lines.push("", "export const releases: Record<string, RawRelease> = {");
keys.forEach((k, n) => {
  lines.push(`  "${k}": { ${Object.keys(FILES).map((name) => `${name}: ${name}${n}`).join(", ")} },`);
});
lines.push("};", "");
writeFileSync(join(out, "index.ts"), lines.join("\n"));
console.log(`lib/content/releases/index.ts lists ${keys.length} release(s).`);
