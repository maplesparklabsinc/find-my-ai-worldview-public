#!/usr/bin/env python3
"""Build content/items.json from research/item-bank.csv.

The CSV (generated by research/build_item_bank.py) is the canonical item data.
items.json is what the app reads. Never edit items.json by hand.

Usage: python3 -I reference/build_content.py   (run from the repo root)
"""
import csv, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "research", "item-bank.csv")
OUT = os.path.join(ROOT, "content", "items.json")

SCORED = ["C1", "C2", "C3", "C4", "C5", "C6"]
STANDARD_FORM = {
    # Order of screens for the standard form. Construct blocks are shuffled at
    # run time (seeded per respondent); items within a block are shuffled too.
    # S1 comes first after the six blocks (v0.4): placed before the release-pace
    # block it primed those items; after them it is not primed by them either,
    # because the blocks come in between in shuffled order for most people.
    "intro": [],
    "blocks": [{"construct": c, "confidence_probe": "D3"} for c in SCORED],
    "pinned_before_block": {},
    "after_blocks": ["S1", "C3-T1", "C4-T1", "C5-T1", "CX-T1", "S3", "S4"],
    # The trade-off cards swap places among themselves per person (v0.6), so
    # CX-T1 isn't always the last one; S1 stays first and S3, S4 stay last.
    "after_blocks_shuffled": ["C3-T1", "C4-T1", "C5-T1", "CX-T1"],
    "outro": ["D11", "D1", "D2", "D4", "D6", "D7", "D8", "D9"],
}


def split(s):
    return [x for x in s.split("|")] if s else []


def main():
    items = []
    with open(SRC, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            items.append({
                "id": r["id"],
                "construct": r["construct"],
                "pole": r["pole"] or None,
                "stem": r["stem"],
                "options": split(r["options"]),
                "rows": split(r["rows"]),
                "short": r["short"] or None,
                "format": r["format"],
                "forms": r["form"].split(","),
                "priority": int(r["priority"]),
                "flags": [x for x in r["flags"].split(",") if x],
                "source": r["source"],
            })
    by_id = {i["id"]: i for i in items}
    for c in SCORED:
        block = [i["id"] for i in items if i["construct"] == c and i["format"] == "L7" and "S" in i["forms"]]
        STANDARD_FORM["blocks"][SCORED.index(c)]["items"] = block
    referenced = STANDARD_FORM["intro"] + STANDARD_FORM["after_blocks"] + STANDARD_FORM["outro"] + ["D3"]
    assert set(STANDARD_FORM["after_blocks_shuffled"]) <= set(STANDARD_FORM["after_blocks"])
    missing = [x for x in referenced if x not in by_id]
    assert not missing, missing
    bundle = {
        "item_bank_version": "0.8.0",
        "likert_labels": ["Strongly disagree", "Disagree", "Somewhat disagree", "Neither agree nor disagree",
                          "Somewhat agree", "Agree", "Strongly agree"],
        "tradeoff_strength_labels": ["Slightly", "Strongly"],
        "definition_text": ("When we say AI, we mean the systems in use today: chatbots and assistants, image and voice tools, "
                            "recommendation systems, and software that makes or supports decisions about people. A few questions "
                            "ask about more capable future AI; those say so. There are no right answers. If you are not sure, go "
                            "with how you lean, or skip it. At the end of each section we will ask how settled your views are."),
        "forms": {"S": STANDARD_FORM},
        "items": items,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(bundle, f, ensure_ascii=False, indent=1)
    n_s = sum(len(b["items"]) for b in STANDARD_FORM["blocks"]) + len(referenced) - 1
    print(f"{len(items)} items -> {OUT}; standard form: {n_s} questions + {len(SCORED)} confidence probes")


if __name__ == "__main__":
    main()
